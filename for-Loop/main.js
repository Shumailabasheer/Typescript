"use strict";
//Loop
for (let i = 1; i < 6; i++) {
    console.log(i);
}
for (let i = 1; i < 10; i++) {
    console.log('Hello world');
}
let number = 5;
for (let i = 1; i <= 10; i++) {
    console.log(`${number} X ${i}`);
}
let fruits = ['mango', 'apple', 'banana', 'orange', 'painapeele'];
for (let i = 0; i < fruits.length; i++) {
    console.log(fruits);
}
for (let i = 0; i < 10; i++) {
    console.log(i);
}
//While Loop
let j = 0;
while (j < 11) {
    console.log(j);
    j++;
}
//do while Loop
let l = 0;
do {
    console.log(l);
    l++;
} while (l < 11);
//difference B/w while and do-while Loop
let i = 12;
while (i < 11) {
    console.log("Hello World");
}
do {
    console.log("Hello World"); //on time run
} while (i < 11);
